class User {
  final int id;
  final String name;
  final String imageUrl;
  final String lastMessage;
  final String time;
  final String lastSeen;

  const User({
    required this.id,
    required this.name,
    required this.imageUrl,
    required this.lastMessage,
    required this.time,
    required this.lastSeen,
  });
}
